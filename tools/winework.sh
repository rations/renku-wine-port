#!/bin/sh
# winework.sh — fast edit/build/test loop on the build machine, with a mandatory mirror back.
#
# A clean `haikuporter -c` build recompiles all of Wine, about ten thousand objects. A change
# does not need one to be tested. haikuporter applies .patchset files with git, so
#   work-<ver>/sources/wine-wine-<ver>   (<ver> from the recipe, see common.sh)
# is a real git repo whose HEAD^{tree} is the patchset's tree, and every source change made in
# it since is visible to git. That makes two things cheap, and checkable:
#   - testing a change: push the files, make the one target, run against the build tree;
#   - not losing work: anything edited only on the build machine shows up in `status`.
# A package is built at a milestone, with a clean build that nothing touches while it runs
# (README.md, "Building"), and then checked with `checkpkg`.
#
# Settings (build host, dev tree, haikuports path): see tools/common.sh.
#
# Usage:
#   winework.sh status          VM edits that are in no dev-tree file or commit (exit 1 if any)
#   winework.sh diff            the VM tree's source diff against its own HEAD
#   winework.sh pull            copy those VM-only edits into the dev tree
#   winework.sh push <file>...  copy dev-tree working file(s) to the VM (paths repo-relative)
#   winework.sh build [target]  incremental make on the VM (default: all)
#   winework.sh sync            make the VM tree's sources equal the dev tree's HEAD
#   winework.sh verify          check that they are equal (exit 1 if not)
#   winework.sh checkpkg        check the built hpkg of the recipe's REVISION
#   winework.sh howto           how to test against the build tree without installing
#
# Why checkpkg. configure sets prefix=/packages/wine-<ver>-<rev>/.self and some objects compile
# that path in, as text (ntdll, wineserver, the tools) or as UTF-16 (the mscoree, mshtml and
# appwiz.cpl lookups build it into wide strings). A package whose binaries hold another
# revision's path works on the build machine and fails everywhere else; that shipped once.
# checkpkg extracts the package and fails if any file holds another revision's path, in either
# form, or if none holds the recipe's.
#
# Exit status: `status` exits 1 when there are unmirrored edits, so hooks can gate on it, and
# 3 when the VM cannot be reached.

set -eu

REPO="$(cd "$(dirname "$0")/.." && pwd)"
. "$REPO/tools/common.sh"
# Paths on the build machine are relative to its home directory, where ssh starts.
WORK="$PORTS/app-emulation/wine/work-$VER/sources/wine-wine-$VER"
PORT=wine-$VER

# Files haikuporter/autoreconf regenerate on every build. They are not edits, and pulling them
# into the dev tree would add generated noise to the patchset. The recipe's BUILD() runs
# autoreconf, so the dev tree's copies of these never reach a build either.
BYPRODUCT='^(configure|include/config\.h\.in)$'
# Untracked build output that is never a source edit. wine.rdef is generated by the recipe's
# INSTALL() from additional-files/wine.rdef.in, so it appears in the work tree after a build.
# include/config.h, include/stamp-h and tools/makedep are written by configure itself, so a
# tree whose configure ran (or failed) shows them before anything is compiled.
NOISE='(^autom4te\.cache/|~$|/(i386|x86_64)-windows/|\.(o|a|so|dll|exe|res)$|^config\.(log|status)$|^wine\.rdef$|^include/(config\.h|stamp-h)$|^tools/makedep$)'

die() { echo "winework: $*" >&2; exit 2; }
remote() { ssh -o BatchMode=yes "$HOST" "cd $WORK && $1"; }
has_path() { awk -v f="$1" '$3 == f { found = 1 } END { exit !found }' "$2"; }
# A PCRE matching the UTF-16LE form of a string (each byte followed by a NUL), for grep -P.
u16() { printf '%s' "$1" | awk '{ for (i = 1; i <= length($0); i++) { c = substr($0, i, 1);
                                  printf "%s\\x00", (c == "." ? "\\." : c) } }'; }
# Remote shell code: prints every /packages/wine-<ver>-N/ path in the files (or, recursively,
# directories) named after it, in text or in UTF-16, one per line.
PATHS_IN="paths_in() { grep -raoh '/packages/wine-$VER-[0-9]*/' \"\$@\" 2>/dev/null;
  LC_ALL=C grep -raohP '$(u16 "/packages/wine-$VER-")(?:[0-9]\\x00)+/\\x00' \"\$@\" 2>/dev/null | tr -d '\\000'; }"
recipe_rev() { sed -n 's/^REVISION="\(.*\)"/\1/p' "$REPO/$RECIPE"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The VM tree's source changes against its own HEAD, one per line, in one ssh round-trip:
#   M <blob> <path>   tracked, modified        A <blob> <path>   new, untracked
#   D - <path>        tracked, deleted
# Byproducts and build output are left out.
vm_changes() {
    ssh -o BatchMode=yes "$HOST" "cd $WORK && sh -s" <<EOF
git diff --name-only HEAD | grep -Ev '$BYPRODUCT' | while IFS= read -r f; do
    if [ -e "\$f" ]; then echo "M \$(git hash-object -- "\$f") \$f"; else echo "D - \$f"; fi
done
git ls-files --others --exclude-standard | grep -Ev '$NOISE' | while IFS= read -r f; do
    echo "A \$(git hash-object -- "\$f") \$f"
done
EOF
}

# What vm_changes must print for the VM tree to equal the dev tree's HEAD: the dev tree's
# diff from the VM tree's HEAD^{tree}, with HEAD's blobs. Sets BASE.
wanted_changes() {
    BASE=$(remote "git rev-parse 'HEAD^{tree}'") || die "cannot reach $HOST"
    git -C "$DEV" cat-file -e "$BASE" 2>/dev/null \
        || die "the VM tree's base $BASE is not a tree in $DEV; it needs a clean build"
    git -C "$DEV" diff --no-renames --name-status "$BASE" HEAD -- . \
            ':(exclude)configure' ':(exclude)include/config.h.in' |
    while IFS="$(printf '\t')" read -r kind f; do
        case $kind in
            D) echo "D - $f" ;;
            *) echo "$kind $(git -C "$DEV" rev-parse "HEAD:$f") $f" ;;
        esac
    done
}

cmd_diff() {
    # Tracked source edits only. -- :(exclude) keeps the regenerated files out.
    remote "git diff HEAD -- . ':(exclude)configure' ':(exclude)include/config.h.in'"
}

# An edit on the VM is mirrored when the dev tree holds the same content, in its working
# files or in its HEAD: then a clean build or a sync loses nothing.
unmirrored() {
    while read -r kind blob f; do
        if [ "$kind" = D ]; then
            [ ! -e "$DEV/$f" ] && continue
            git -C "$DEV" cat-file -e "HEAD:$f" 2>/dev/null || continue
        else
            [ -f "$DEV/$f" ] && [ "$(git -C "$DEV" hash-object -- "$f")" = "$blob" ] && continue
            [ "$(git -C "$DEV" rev-parse -q --verify "HEAD:$f" 2>/dev/null)" = "$blob" ] && continue
        fi
        echo "$kind $f"
    done
}

cmd_status() {
    vm_changes > "$TMP/vm" 2>/dev/null || { echo "winework: cannot reach $HOST" >&2; return 3; }
    unmirrored < "$TMP/vm" > "$TMP/un"
    if [ ! -s "$TMP/un" ]; then
        echo "VM work tree: no unmirrored source edits ($(wc -l < "$TMP/vm") file(s) differ from its HEAD, all in the dev tree)."
        return 0
    fi
    echo "UNMIRRORED EDITS on $HOST — these exist in no dev-tree file or commit."
    echo "\`haikuporter -c\` and \`winework.sh sync\` lose them. Run 'winework.sh pull' first."
    sed 's/^M /  modified: /; s/^A /  new:      /; s/^D /  deleted:  /' "$TMP/un"
    return 1
}

cmd_pull() {
    vm_changes > "$TMP/vm" || die "cannot reach $HOST"
    unmirrored < "$TMP/vm" > "$TMP/un"
    [ -s "$TMP/un" ] || { echo "Nothing to pull: every VM edit is already in the dev tree."; return 0; }
    sed -n 's/^[MD] //p' "$TMP/un" > "$TMP/tracked"
    if [ -s "$TMP/tracked" ]; then
        remote "git diff HEAD -- $(tr '\n' ' ' < "$TMP/tracked")" > "$TMP/patch"
        echo "Applying $(grep -c '^+++ ' "$TMP/patch") changed file(s) to $DEV:"
        git -C "$DEV" apply --stat "$TMP/patch"
        git -C "$DEV" apply --3way "$TMP/patch"
    fi
    sed -n 's/^A //p' "$TMP/un" | while read -r f; do
        if [ -e "$DEV/$f" ]; then
            echo "NOT copied, the dev tree has a different $f: compare them by hand" >&2
        else
            mkdir -p "$DEV/$(dirname "$f")"
            scp -q "$HOST:$WORK/$f" "$DEV/$f"
            echo "copied new file $f"
        fi
    done
    echo
    echo "Now commit in $DEV (--amend into the right patch, or a new commit),"
    echo "then regenerate the patchset and bump REVISION."
}

cmd_push() {
    [ $# -gt 0 ] || { echo "push: need at least one repo-relative path" >&2; exit 2; }
    for f in "$@"; do
        [ -f "$DEV/$f" ] || { echo "push: $DEV/$f does not exist" >&2; exit 2; }
        remote "mkdir -p '$(dirname "$f")'"
        scp -q "$DEV/$f" "$HOST:$WORK/$f"
        echo "pushed $f"
    done
}

cmd_build() {
    target=${1:-all}
    # Runs make in place, outside the chroot. `haikuporter -E` only enters the chroot
    # interactively: driven over ssh it set up and tore down without running the commands piped
    # into it (seen 2026-11-11). make is safe outside: the Makefile has no chroot paths.
    # configure is NOT: run outside, it found nasm and libxkbregistry, which the chroot lacks,
    # and rewrote include/config.h. configure runs only inside haikuporter.
    echo "Incremental make '$target' in the work tree on $HOST..."
    remote "make -j\$(nproc) $target"
}

cmd_verify() {
    wanted_changes | sort -k3 > "$TMP/want"
    vm_changes | sort -k3 > "$TMP/have" || die "cannot reach $HOST"
    if cmp -s "$TMP/want" "$TMP/have"; then
        echo "VM work tree = dev tree HEAD $(git -C "$DEV" rev-parse --short HEAD)" \
             "(tree $(git -C "$DEV" rev-parse --short 'HEAD^{tree}')), apart from autoreconf output."
        return 0
    fi
    echo "VM work tree differs from dev tree HEAD (< dev HEAD, > VM):"
    diff "$TMP/want" "$TMP/have" | grep '^[<>]' || true
    return 1
}

cmd_sync() {
    cmd_status > "$TMP/status" || { cat "$TMP/status"; die "not syncing over VM-only edits"; }
    wanted_changes | sort -k3 > "$TMP/want"
    vm_changes | sort -k3 > "$TMP/have"
    n=0
    # Files the dev tree's HEAD changes: give the VM HEAD's content, unless it has it already
    # (rewriting an identical file would only make make rebuild what depends on it).
    while read -r kind blob f; do
        if [ "$kind" = D ]; then
            grep -qxF "D - $f" "$TMP/have" && continue
            remote "rm -f -- '$f'"; echo "deleted $f"
        else
            grep -qxF "$kind $blob $f" "$TMP/have" && continue
            git -C "$DEV" show "HEAD:$f" |
                ssh -o BatchMode=yes "$HOST" "cd $WORK && mkdir -p '$(dirname "$f")' && cat > '$f'"
            echo "updated $f"
        fi
        n=$((n + 1))
    done < "$TMP/want"
    # Files the VM changed but the dev tree's HEAD does not (an uncommitted push, say): put
    # back the VM HEAD's content. Each is in the dev tree's working files, or status said so.
    while read -r kind blob f; do
        has_path "$f" "$TMP/want" && continue
        if [ "$kind" = A ]; then remote "rm -f -- '$f'"; else remote "git checkout HEAD -- '$f'"; fi
        echo "reverted $f"
        n=$((n + 1))
    done < "$TMP/have"
    echo "$n file(s) changed on $HOST."
    cmd_verify
}

cmd_checkpkg() {
    rev=$(recipe_rev)
    hpkg="$PORTS/packages/$PORT-$rev-x86_64.hpkg"
    echo "Checking $PORT-$rev-x86_64.hpkg on $HOST..."
    ssh -o BatchMode=yes "$HOST" "sh -s" <<EOF
set -e
p=$hpkg
package list -i "\$p" > /tmp/winework-info  # fails on a damaged file ("Invalid magic")
grep -E '^\s*(requires|provides): ' /tmp/winework-info
d=/tmp/winework-pkgcheck
rm -rf "\$d"; mkdir "\$d"
package extract -C "\$d" "\$p"
$PATHS_IN
echo "package paths compiled in, as text or UTF-16 (count, path):"
paths_in "\$d" > /tmp/winework-paths
sort /tmp/winework-paths | uniq -c
bad=\$(sort -u /tmp/winework-paths | grep -vx '/packages/wine-$VER-$rev/' || true)
good=\$(grep -cx '/packages/wine-$VER-$rev/' /tmp/winework-paths || true)
rm -rf "\$d" /tmp/winework-paths
[ -z "\$bad" ] || { echo "FAIL: another revision's path is in the package: \$bad"; exit 1; }
[ "\$good" -gt 0 ] || { echo "FAIL: nothing holds /packages/wine-$VER-$rev/"; exit 1; }
echo "OK: /packages/wine-$VER-$rev/ appears \$good times, no other revision's path."
EOF
}

cmd_howto() {
    cat <<EOF
Testing a build-tree Wine without packaging or installing:

  Wine sets build_dir when its ntdll.so sits under <tree>/dlls/ntdll
  (dlls/ntdll/unix/loader.c:392). When build_dir is set, dll_dir — the installed
  /boot/system/lib/wine — is NOT added to the search path (loader.c:307), so the build tree
  wins outright. Nothing needs to be installed or overwritten.

  vstbridge picks its loader from \$WINELOADER when that path is executable
  (src/plugin/utils.cpp:106-111), so pointing it at the build tree tests the whole stack:

    export WINELOADER=~/$WORK/loader/wine
    # then start jackDAW from that same shell

  Unset WINELOADER to go back to the installed package.

  NOTE: WINEDLLPATH does NOT work for this. Its entries are appended *after* dll_dir
  (loader.c:307-313), so an installed dxgi.dll always wins over one dropped in via
  WINEDLLPATH. Do not try to override a builtin that way.
EOF
}

case "${1:-}" in
    howto|"") ;;
    push|pull|sync|verify) need_host; need_dev ;;
    status) need_host; need_dev ;;
    diff|build|checkpkg) need_host ;;
esac

case "${1:-}" in
    status)   shift; cmd_status "$@" ;;
    diff)     shift; cmd_diff "$@" ;;
    pull)     shift; cmd_pull "$@" ;;
    push)     shift; cmd_push "$@" ;;
    build)    shift; cmd_build "$@" ;;
    sync)     shift; cmd_sync "$@" ;;
    verify)   shift; cmd_verify "$@" ;;
    checkpkg) shift; cmd_checkpkg "$@" ;;
    howto)    shift; cmd_howto "$@" ;;
    *) sed -n '2,25p' "$0"; exit 2 ;;
esac
